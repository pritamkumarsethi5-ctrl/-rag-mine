"""RAG-Mine FastAPI application (SIMULATION MODE).

Run:  uvicorn app.main:app --host 127.0.0.1 --port 8000
"""
from __future__ import annotations

import asyncio
import json
import os
from contextlib import asynccontextmanager
from typing import Optional

from fastapi import FastAPI, Query, Request, WebSocket, WebSocketDisconnect
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse, PlainTextResponse
from fastapi.staticfiles import StaticFiles

from . import config
from .schemas import (NavControlRequest, NavStartRequest, RoverCommandRequest, ScenarioRequest, SpeedRequest,
                      ThresholdUpdate)
from .service import ApiError, Service
from .simulation import Simulation
from .store import SqliteStore


class Hub:
    """Tracks WebSocket clients and broadcasts one serialised snapshot to all of them."""

    def __init__(self) -> None:
        self.clients: set[WebSocket] = set()

    async def connect(self, ws: WebSocket) -> None:
        await ws.accept()
        self.clients.add(ws)

    def drop(self, ws: WebSocket) -> None:
        self.clients.discard(ws)

    async def broadcast(self, snap: dict) -> None:
        if not self.clients:
            return
        text = json.dumps(snap, separators=(",", ":"))
        dead = []
        for ws in list(self.clients):
            try:
                await ws.send_text(text)
            except Exception:
                dead.append(ws)
        for ws in dead:
            self.drop(ws)


def create_app(autostart: bool | None = None, store: SqliteStore | None = None) -> FastAPI:
    sim = Simulation(store=store)
    svc = Service(sim)
    hub = Hub()
    run_loop = config.AUTOSTART if autostart is None else autostart

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        if run_loop:
            sim.start()

        async def loop() -> None:
            while True:
                await asyncio.sleep(sim.settings.tick_interval_s)
                try:
                    sim.tick()
                    await hub.broadcast(sim.snapshot())
                except Exception as e:  # keep the loop alive; surface in health
                    sim.loop_error = repr(e)

        task = asyncio.create_task(loop())
        try:
            yield
        finally:
            task.cancel()
            if sim.store:
                sim.store.close()

    app = FastAPI(
        title="RAG-Mine API (SIMULATION MODE)",
        version="1.0.0",
        description="All data is generated by a local simulation engine. Nothing here is a real mine measurement.",
        lifespan=lifespan,
    )
    app.add_middleware(CORSMiddleware, allow_origins=config.CORS_ORIGINS, allow_methods=["*"], allow_headers=["*"])
    app.state.sim, app.state.svc, app.state.hub = sim, svc, hub

    @app.exception_handler(ApiError)
    async def api_error(_: Request, exc: ApiError):
        return JSONResponse(status_code=exc.status, content={"detail": exc.detail, "simulated": True})

    async def push() -> None:
        await hub.broadcast(sim.snapshot())

    # ---- read -----------------------------------------------------------------
    @app.get("/api/health")
    async def health():
        return svc.health()

    @app.get("/api/mine/map")
    async def mine_map():
        return svc.mine_map()

    @app.get("/api/telemetry/latest")
    async def telemetry_latest():
        return svc.telemetry_latest()

    @app.get("/api/telemetry/history")
    async def telemetry_history(metrics: Optional[str] = None, sensor: Optional[str] = None, range: Optional[str] = None,
                                from_: Optional[str] = Query(default=None, alias="from"), to: Optional[str] = None,
                                max_points: int = Query(default=240, ge=10, le=1000)):
        return svc.telemetry_history(metrics, sensor, range, from_, to, max_points)

    @app.get("/api/telemetry/history.csv", response_class=PlainTextResponse)
    async def telemetry_history_csv(metrics: Optional[str] = None, sensor: Optional[str] = None, range: Optional[str] = None,
                                    from_: Optional[str] = Query(default=None, alias="from"), to: Optional[str] = None):
        return PlainTextResponse(svc.history_csv(metrics, sensor, range, from_, to), media_type="text/csv")

    @app.get("/api/workers")
    async def workers():
        return svc.workers()

    @app.get("/api/workers/{worker_id}")
    async def worker(worker_id: str):
        return svc.worker(worker_id)

    @app.get("/api/rover")
    async def rover():
        return svc.rover()

    @app.get("/api/alerts")
    async def alerts(severity: Optional[str] = None, category: Optional[str] = None, status: Optional[str] = None,
                     q: Optional[str] = None, limit: int = 200):
        return svc.alerts(severity, category, status, q, limit)

    @app.get("/api/routes")
    async def routes(worker_id: str, dest: Optional[str] = None, mode: str = "normal"):
        return svc.routes(worker_id, dest, mode)

    @app.get("/api/simulation/status")
    async def simulation_status():
        return svc.sim_status()

    @app.get("/api/analytics")
    async def analytics(range: Optional[str] = "1h"):
        return svc.analytics(range)

    @app.get("/api/thresholds")
    async def thresholds():
        return svc.thresholds()

    @app.get("/api/hardware/status")
    async def hardware():
        return svc.health()["hardware"]

    # ---- control -----------------------------------------------------------------
    @app.post("/api/simulation/start")
    async def start():
        r = svc.start(); await push(); return r

    @app.post("/api/simulation/pause")
    async def pause():
        r = svc.pause(); await push(); return r

    @app.post("/api/simulation/reset")
    async def reset():
        r = svc.reset(); await push(); return r

    @app.post("/api/simulation/speed")
    async def speed(body: SpeedRequest):
        r = svc.set_speed(body.speed); await push(); return r

    @app.post("/api/simulation/scenario")
    async def scenario(body: ScenarioRequest):
        r = svc.scenario(body.scenario, body.segment_id, body.gas, body.zone); await push(); return r

    @app.put("/api/thresholds")
    async def put_threshold(body: ThresholdUpdate):
        vals = body.model_dump(exclude={"gas"}, exclude_none=True)
        r = svc.update_threshold(body.gas, **vals); await push(); return r

    @app.post("/api/thresholds/reset")
    async def reset_thresholds():
        r = svc.reset_thresholds(); await push(); return r

    @app.post("/api/rover/command")
    async def rover_command(body: RoverCommandRequest):
        r = svc.rover_command(body.command, body.speed_mps, body.duration_s); await push(); return r

    @app.post("/api/navigation/start")
    async def nav_start(body: NavStartRequest):
        r = svc.nav_start(body.worker_id, body.dest_node, body.mode, body.alternate); await push(); return r

    @app.post("/api/navigation/control")
    async def nav_control(body: NavControlRequest):
        r = svc.nav_control(body.worker_id, body.action); await push(); return r

    @app.post("/api/alerts/{alert_id}/acknowledge")
    async def ack(alert_id: str):
        r = svc.alert_acknowledge(alert_id); await push(); return r

    @app.post("/api/alerts/{alert_id}/resolve")
    async def resolve(alert_id: str):
        r = svc.alert_resolve(alert_id); await push(); return r

    # ---- live telemetry ----------------------------------------------------------
    @app.websocket("/ws/telemetry")
    async def ws_telemetry(ws: WebSocket):
        await hub.connect(ws)
        try:
            await ws.send_text(json.dumps(sim.snapshot(), separators=(",", ":")))
            while True:
                await ws.receive_text()  # clients may send keep-alive pings; content is ignored
        except WebSocketDisconnect:
            pass
        except Exception:
            pass
        finally:
            hub.drop(ws)

    # Serve the built frontend if present (single-command run).
    dist = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "frontend", "dist"))
    if os.path.isdir(dist):
        app.mount("/", StaticFiles(directory=dist, html=True), name="ui")

    return app


def _default_store() -> SqliteStore | None:
    return SqliteStore(config.DB_PATH) if config.PERSIST_ENABLED else None


app = create_app(store=_default_store())
